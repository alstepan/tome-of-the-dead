OPTIONS = OPTIONS_DG


# ===========================================================================
def main(options=None, tag="art19", board="F3s", span="D-G", script="tools/gen_art19.py",
         extra_sheet=None) -> int:
    """Validate, cost and render one option set. gen_art19b.py calls this with H-M (tag art19b);
    `extra_sheet` = (filename, {letter: (title, fn)}) for a combined sheet."""
    OPTIONS = options or OPTIONS_DG
    for d in (GRID_OUT, ANIM):
        os.makedirs(d, exist_ok=True)
    bad = []
    res, pk, blk = {}, {}, {}
    pool = sum(N.pool(H, w, 0, BW, f) for _n, _p, f, w in FRAMES)
    with tempfile.TemporaryDirectory() as td:
        for o, (title, fn) in OPTIONS.items():
            fr, hem = fn()
            res[o] = fr
            raws = []
            for name, pose, flag, w in FRAMES:
                b = fr[pose]
                if b.shape != (H, w):
                    bad.append(f"{o} {name}: shape {b.shape}")
                if not b.any():
                    bad.append(f"{o} {name}: empty")
                solid = S.make_mask(b, outline=True)
                nm = f"{name}_{o.lower()}"
                g = os.path.join(GRID_OUT, nm + ".grid")
                with open(g, "w") as fh:
                    fh.write(A.grid_text(nm, b, solid, f"GHOST {o} {title} {pose}", INKS[0][1],
                                         f"ART19 ghost option {o} ({title}), {flag}, ax 0, body {BW}; "
                                         f"{script}; not imported")
                             .replace("tools/gen_art2_options.py", script))
                for _lab, ink in INKS:
                    raw = A.pack_check(f"{nm}_{ink[1:]}", g, b, solid, ink, td)
                raws.append((nm, raw))
            pk[o], blk[o] = G.packed_kind(raws, td)
            f1, f2 = fr["FLOAT1"], fr["FLOAT2"]
            if not np.array_equal(f2[1:hem + 1], f1[:hem]) or f1[H - 1].any():
                bad.append(f"{o}: bob rule (FLOAT2 = FLOAT1 + 1 px above the hem)")
            # anchor: ax 0 everywhere, so the body column must stay inside 0..BW-1 on the 24-wide
            # frames and the lunge may only add reach on the right (x >= BW is the reach).
            lu = fr["LUNGE"]
            if lu[:, :BW].sum() == 0 or not lu[:, BW:].any():
                bad.append(f"{o}: lunge reach (ax 0: body in x 0..23, reach in x 24..31)")
        gf = dict(zp.game_frames())
        cur, cur_blk = G.packed_kind([(n, gf[n]) for n in NAMES], td)
    ref = G.cur_bitmaps()

    def fit(d):
        if d <= 0:
            return "saves" if d < 0 else "same"
        if d <= SRC6_FREE:
            return f"fits the {SRC6_FREE} B free"
        pages = -(-(d - SRC6_FREE) // 256)
        return (f"OVER by {d - SRC6_FREE} B -> +{pages} SRC6 page: POOL_CAP -{256 * pages} on EVERY level "
                f"(D8 slack {POOL_SLACK_D8:,} -> {POOL_SLACK_D8 - 256 * pages:,})")

    L = [f"# {tag.upper()} Ghost side-view options {span} (dementor-like) — costs ({script}).",
         "# pool = src/defs.asm FRM formula (both facings, one shift per flag); packed = zx0 with",
         "# the zx0_sources.partition rule (<= 4 frames a block), today's frames from zx0_pack.game_frames.",
         f"# SRC6: {SRC6_FREE} B free of 14 pages; each further page costs 256 B of POOL_CAP on EVERY level.",
         "",
         "GHOST frames (src/frames.asm KFID_GHOST, also K_POLTERGEIST): float1 24x32 WK0, float2 24x32 MOT,",
         "  lunge 32x32 STA, hurt 24x32 STA, dead 24x32 STA (own DEAD); ax 0, body 24.",
         f"  pool {pool} B per Ghost level (384 + 896 + 512 + 384 + 384) -- UNCHANGED by every option (drop-in)",
         "  frame ids 0 (144/144 stays), engine 0, sequences 0, pool 0: only the packed SRC6 bytes move.",
         f"  today  packed {cur} B  ({', '.join(cur_blk)})"]
    for o, (title, _fn) in OPTIONS.items():
        d = pk[o] - cur
        L.append(f"  {o} {title:15s} packed {pk[o]} B  delta {d:+d} B SRC6  ({fit(d)})  [{', '.join(blk[o])}]")
    with open(os.path.join(OUT, "costs.txt" if tag == "art19" else f"costs_{tag[5:]}.txt"), "w") as fh:
        fh.write("\n".join(L) + "\n")

    # ---- board ---------------------------------------------------------------
    bd = [N.heading(f"{board} {tag.upper()} — GHOST, SIDE VIEW, DEMENTOR-LIKE (OPTIONS {span})"),
          N.sub("Concept, not imported. Continues ART17 A/B/C. Drop-in for the 5 Ghost frames: same "
                "slots, sizes, flags (FLOAT1 WK0, FLOAT2 MOT, LUNGE / HURT / DEAD STA), ax 0, cycles; "
                "pool and frame ids unchanged. Profiles face right (left = engine mirror). FLOAT2 = "
                "FLOAT1 1 px lower, only the hem moves (the idle bob). Ink $45 bright cyan (K_GHOST); "
                "the Poltergeist draws the same frames in $03. One ink + black paper: every cell "
                "2-colour, no FLASH."),
          N.heading(f"{board} GHOST TODAY"),
          N.sub(f"packed {cur} B"),
          N.row([S.svg_artboard_html(b, INKS[0][1], n.upper().replace("_", " ")) for n, b in ref.items()])]
    for o, (title, _fn) in OPTIONS.items():
        bd.append(N.heading(f"{board} GHOST {o} — {title}"))
        bd.append(N.sub(f"packed {pk[o]} B (today {cur} B, {pk[o] - cur:+d} B SRC6; pool +0)"))
        bd.append(N.row([S.svg_artboard_html(res[o][p], INKS[0][1], f"GHOST {o} {p}")
                         for _n, p, _f, _w in FRAMES]))
        cells = []
        for lab, seq in G.SEQS.items():
            glide = lab == "FLY"
            rows = [G.strip(res[o], seq, fc, glide)[0] for fc in (1, -1)]
            _t, W, Hh = G.strip(res[o], seq, 1, glide)
            cells.append(N.anim_svg(rows, INKS[0][1], W, Hh, f"GHOST {o} {lab}", dur_ms=120))
            G.gif(os.path.join(ANIM, f"ghost_{o.lower()}_{lab.split('/')[0].lower()}.gif"), rows, W, Hh,
                  INKS[0][1])
        rows = [G.strip(res[o], G.SEQS["IDLE"], 1, False)[0]]
        _t, W, Hh = G.strip(res[o], G.SEQS["IDLE"], 1, False)
        cells.append(N.anim_svg(rows, INKS[1][1], W, Hh, f"POLTERGEIST {o} IDLE ($03)", dur_ms=120))
        bd.append(N.row(cells))
    with open(os.path.join(OUT, f"{tag}_ghost.svg.html"), "w") as fh:
        fh.write("\n".join(bd) + "\n")
    rows = [("GHOST today", [(b, INKS[0][1]) for b in ref.values()])]
    rows += [(f"GHOST {o} {t}", [(res[o][p], INKS[0][1]) for _n, p, _f, _w in FRAMES])
             for o, (t, _) in OPTIONS.items()]
    G.sheet(os.path.join(OUT, f"{tag}.png"), rows)
    if extra_sheet:
        fn_, opts_ = extra_sheet
        allr = [rows[0]] + [(f"GHOST {o} {t}", [(f()[0][p], INKS[0][1]) for _n, p, _f, _w in FRAMES])
                            for o, (t, f) in opts_.items()]
        G.sheet(os.path.join(OUT, fn_), allr)
    # the same sheet in the Poltergeist ink, so the $03 read is reviewable too
    G.sheet(os.path.join(OUT, f"{tag}_poltergeist.png"),
            [(f"POLTERGEIST {o}", [(res[o][p], INKS[1][1]) for _n, p, _f, _w in FRAMES])
             for o in OPTIONS])
    print("\n".join(L[5:]))
    if bad:
        print("FAIL:\n  " + "\n  ".join(bad))
        return 1
    print("OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
