def i_lunge(f2, _unused):
    """Rows 0-12 of FLOAT2 shift right 5 (row 13 by 3, 14 by 1): the neck stretches; the
    mouth-ring widens and three motes are drawn in from x 29-31."""
    b = np.zeros((H, 32), bool)
    b[:, :24] = f2
    for y, dx in [(y, 5) for y in range(0, 14)] + [(14, 3), (15, 1)]:
        row = np.zeros(32, bool)
        row[dx:] = b[y, :32 - dx]
        b[y] = row | (b[y] if y >= 13 else False)
    # fill the neck so the stretched hood stays joined to the robe
    for y, x0, x1 in ((12, 9, 13), (13, 9, 15), (14, 8, 14), (15, 8, 12)):
        b[y, x0:x1] = True
    b = G.patch(b, 5, 16, """
oooooooo
oo####oo
o#oooo#o
o#oooo#o
o#oooo#o
oo####oo
""")
    b = G.patch(b, 6, 29, """
.#.
#..
..#
.#.
""")
    return b


