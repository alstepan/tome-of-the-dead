def main() -> int:
    os.makedirs(GRID_OUT, exist_ok=True)
    game = dict(zp.game_frames())
    built, cost = [], []
    with tempfile.TemporaryDirectory() as td:
        new = {}
        for grp, name, cap, fn, ink, flag, note in FRAMES:
            bm = fn().astype(bool)
            assert bm.shape == (48, 24), name
            solid = S.make_mask(bm, outline=True)
            gpath = os.path.join(GRID_OUT, name + ".grid")
            with open(gpath, "w") as f:
                f.write(A.grid_text(name, bm, solid, cap, ink, note)
                        .replace("gen_art2_options", "gen_art3_options"))
            raw = A.pack_check(name, gpath, bm, solid, ink, td)   # clash + round-trip
            new[name] = raw
            if flag != "MOCK":
                blk = b"".join(game.get(n) or new[n] for n in BLOCK[name])
                dpk = A.packed(blk + raw, td) - (A.packed(blk, td) if blk else 0)
                cost.append(f"{name:14s} {flag}  pool {POOL[flag]:4d}  raw {len(raw)}  packed +{dpk}  ; {note}")
            built.append((grp, name, cap, bm, solid, ink, note))
    with open(os.path.join(OUT, "costs.txt"), "w") as f:
        f.write("# gen_art3_options.py — pool per frame (SYM climb 288, WK0 576, WK4 768);"
                " packed = ZX0 delta in the kind's SRC6 block\n" + "\n".join(cost) + "\n")
    print("\n".join(cost))
    sheet(built)
    anims()
    return 0


TITLES = {"A1": "A1  SHARED body-neutral climb (one pair, kind ink)",
          "A2": "A2  per-kind climb pairs (Vampire reuses the Necro pair)",
          "B": "B  walk in-betweens (W3 even slot WK4, W4 odd slot WK0)"}


def sheet(built):
    scale, rows = 3, []
    for grp in ("A1", "A2", "B"):
        cells = []
        for g, name, cap, bm, solid, ink, note in built:
            if g != grp:
                continue
            p = A.panel(bm, solid, ink, scale)
            c = Image.new("RGB", (max(p.width, 110) + 8, p.height + 28), (16, 16, 24))
            c.paste(p, (4, 4))
            d = ImageDraw.Draw(c)
            d.text((4, p.height + 6), cap, fill=(220, 220, 230))
            d.text((4, p.height + 16), note, fill=(140, 140, 160))
            cells.append(c)
        r = Image.new("RGB", (sum(c.width for c in cells), cells[0].height + 18), (16, 16, 24))
        ImageDraw.Draw(r).text((4, 4), TITLES[grp], fill=(255, 255, 120))
        x = 0
        for c in cells:
            r.paste(c, (x, 18))
            x += c.width
        rows.append(r)
    sh = Image.new("RGB", (max(r.width for r in rows), sum(r.height for r in rows)), (16, 16, 24))
    y = 0
    for r in rows:
        sh.paste(r, (0, y))
        y += r.height
    sh.save(os.path.join(OUT, "art3_options.png"))
    html = ["<!-- CONCEPT art3 options (tools/gen_art3_options.py) — review only, not importable -->"]
    for grp in ("A1", "A2", "B"):
        html.append(f"<h2>{TITLES[grp]}</h2>")
        html += [S.svg_artboard_html(bm, ink, cap.replace(" ", "_"))
                 for g, _n, cap, bm, _s, ink, _no in built if g == grp]
    with open(os.path.join(OUT, "art3_options.svg.html"), "w") as f:
        f.write("\n".join(html) + "\n")


# ===========================================================================
# GIFs. Walk: 4 px per tick (1 cycle entry per tick); three rows = current
# 2-frame, B3, B4. Climb: on a ladder, 4 px up per tick.
# ===========================================================================
def _blit(a, bm, x, y, ink_hex):
    colour, bright = S.INK_MAP[ink_hex]
    solid = S.make_mask(bm, outline=True)
    hh, ww = bm.shape
    sub = a[y:y + hh, x:x + ww]
    sub[solid] = (0, 0, 0)
    sub[bm] = S.spec_rgb(colour, bright)


def walk_gif(kind, ink, cycles, fname, scale=3):
    fr = {n: load(f"{kind}_walk{n}") if n <= 2 else
          dict((b[1], b[3]) for b in BUILT)[f"{kind}_walk{n}"] for n in (1, 2, 3, 4)}
    w, h = 112, 50 * len(cycles)
    imgs = []
    for t in range(16):
        a = np.full((h, w, 3), (16, 16, 24), np.uint8)
        for i, (_lab, cyc) in enumerate(cycles):
            y0 = 50 * i
            a[y0 + 48, :] = (60, 60, 120)
            x = 8 + (4 * t) % 72
            _blit(a, fr[cyc[t % len(cyc)]], x, y0, ink)
        im = Image.fromarray(a).resize((w * scale, h * scale), Image.NEAREST)
        d = ImageDraw.Draw(im)
        for i, (lab, _c) in enumerate(cycles):
            d.text((4, 50 * i * scale + 2), lab, fill=(255, 255, 120))
        imgs.append(im)
    imgs[0].save(os.path.join(OUT, fname), save_all=True, append_images=imgs[1:],
                 duration=150, loop=0)


def climb_gif(fname, sets, scale=3):
    w, h = 36 * len(sets), 96
    imgs = []
    for t in range(12):
        a = np.full((h, w, 3), (16, 16, 24), np.uint8)
        for i, (_lab, frames, ink) in enumerate(sets):
            x0 = 36 * i + 6
            a[:, x0 + 1] = a[:, x0 + 22] = (215, 0, 0)          # rails (LADDER $02)
            for ry in range((t * 4) % 8, h, 8):
                a[ry, x0 + 1:x0 + 23] = (215, 0, 0)
            _blit(a, frames[t % len(frames)], x0, 40 - 0, ink)
        im = Image.fromarray(a).resize((w * scale, h * scale), Image.NEAREST)
        d = ImageDraw.Draw(im)
        for i, (lab, _f, _k) in enumerate(sets):
            d.text((36 * i * scale + 4, 4), lab, fill=(255, 255, 120))
        imgs.append(im)
    imgs[0].save(os.path.join(OUT, fname), save_all=True, append_images=imgs[1:],
                 duration=200, loop=0)


